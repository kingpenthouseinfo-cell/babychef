import { chromium } from 'playwright-core';
import fs from 'fs';
const D = '/tmp/claude-0/up6/design_handoff_baby_chef_studio/design';
const R = '/home/user/babychef/node_modules';
const b = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium_headless_shell-1194/chrome-linux/headless_shell', args: ['--no-sandbox', '--allow-file-access-from-files'] });
const [file, out, w, h] = process.argv.slice(2);
const p = await b.newPage({ viewport: { width: +w || 1500, height: +h || 1000 } });
p.on('pageerror', e => console.log('PAGEERR', e.message.slice(0, 200)));
await p.route('**/*', async r => {
  const u = r.request().url();
  if (u.includes('react@18.3.1/umd/react.production.min.js')) return r.fulfill({ body: fs.readFileSync(R + '/react/umd/react.production.min.js'), contentType: 'application/javascript' });
  if (u.includes('react-dom@18.3.1/umd/react-dom.production.min.js')) return r.fulfill({ body: fs.readFileSync(R + '/react-dom/umd/react-dom.production.min.js'), contentType: 'application/javascript' });
  if (u.includes('@babel/standalone')) return r.fulfill({ body: fs.readFileSync('/tmp/claude-0/babel/node_modules/@babel/standalone/babel.min.js'), contentType: 'application/javascript' });
  if (u.startsWith('https://fonts.')) return r.abort();
  return r.continue();
});
await p.goto('file://' + D + '/' + encodeURI(file), { waitUntil: 'load' });
await p.waitForTimeout(3500);
const hgt = await p.evaluate(() => document.documentElement.scrollHeight);
console.log('height', hgt);
await p.screenshot({ path: out, fullPage: true });
await b.close();
